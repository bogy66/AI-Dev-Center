def adc_localized_title(app, need, needs, *args, **kwargs):
    """Sphinx-Needs dynamic function backing the `title_display` field.

    Registered in conf.py as that field's predicate default for every
    real Need type. Returns the German title when the active build's
    `language` config is "de" AND a translation entry exists for this
    Need's id; otherwise returns the Need's own original title
    unchanged -- so an untranslated Need is never blank and never shows
    a placeholder, it simply shows English. i18n_completeness.py's
    build-finished gate is what ensures this fallback can never actually
    reach a shipped German build unnoticed.
    """
    need_id = need.get("id")
    if app.config.language == "de" and need_id in TITLES_DE:
        return TITLES_DE[need_id]
    return need.get("title", "")
