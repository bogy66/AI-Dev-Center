"""Central Need-title localization for the bilingual ADC Requirements site.

OC-ADC-REQUIREMENTS-BILINGUAL-EN-DE-001 / -002.

Sphinx-Needs stores a Need's title as directive metadata, not as an
ordinary docutils paragraph node -- so it is NEVER picked up by Sphinx's
standard gettext extraction (confirmed empirically: `sphinx-build -b
gettext` on this tree extracts every Requirement's body/description
paragraph but not one single Requirement title). Ordinary body prose is
therefore localized through the standard .po/.mo mechanism; titles need
this small, explicit, additive side-table instead.

This module never mutates a Need's own `title` field (the predecessor
task's in-memory Need-title-mutation approach was already shown to be
unsupported/fragile by an earlier, unrelated task -- see
svg_status_background.py's docstring). Instead it exposes a *new*,
purely-additive `title_display` field (wired in conf.py exactly like
`implementation_state`/`adc_impl_state_display`), which every card layout
and needtable `:columns:` list uses in place of the raw `title` column
where localization matters. The underlying `title` field, and therefore
every internal Sphinx-Needs identity/cross-reference/link mechanism that
keys off it, is completely untouched.

TITLES_DE is deliberately a flat {need_id: german_title} dict, not a
second Requirements tree: a missing entry simply falls back to the
original English title (never an error, never a blank) -- but see
i18n_completeness.py, which fails a German build outright if any real,
non-pilot Need id is missing here, so "missing -> silent English
fallback" can never actually ship in a German build unnoticed.
"""

